// ---------------- LPI2C0 master ----------------
static void LPI2C0_init(void)
{
    PCC->PCCn[PCC_PORTA_INDEX] |= PCC_PCCn_CGC_MASK;
    PORTA->PCR[2] = PORT_PCR_MUX(3);                       // PTA2 = LPI2C0_SDA (ALT3)
    PORTA->PCR[3] = PORT_PCR_MUX(3);                       // PTA3 = LPI2C0_SCL (ALT3)

    PCC->PCCn[PCC_LPI2C0_INDEX] &= ~PCC_PCCn_CGC_MASK;
    PCC->PCCn[PCC_LPI2C0_INDEX] |= PCC_PCCn_PCS(2) | PCC_PCCn_CGC_MASK;   // functional clock = SIRCDIV2 8 MHz

    LPI2C0->MCR = LPI2C_MCR_RST_MASK;                      // reset master
    LPI2C0->MCR = 0;
    LPI2C0->MCFGR1 = LPI2C_MCFGR1_PRESCALE(0);             // 2-pin open drain (PINCFG = 0)
    LPI2C0->MCFGR2 = 0;
    // SCL ~ 8 MHz / (CLKLO+1 + CLKHI+1 + 2) = 8 MHz / 74 = 108 kHz
    LPI2C0->MCCR0 = LPI2C_MCCR0_CLKLO(39) | LPI2C_MCCR0_CLKHI(31) | LPI2C_MCCR0_SETHOLD(15) | LPI2C_MCCR0_DATAVD(7);
    LPI2C0->MFCR  = LPI2C_MFCR_TXWATER(0) | LPI2C_MFCR_RXWATER(0);
    LPI2C0->MCR   = LPI2C_MCR_MEN_MASK;                    // master enable
}

static int i2c_push(uint32_t word)                         // wait for TX FIFO room, then push one command/data word
{
    uint32_t t0 = dwt_now();
    while ((LPI2C0->MSR & LPI2C_MSR_TDF_MASK) == 0) {
        if (LPI2C0->MSR & LPI2C_MSR_NDF_MASK) return -1;   // slave did not ACK
        if (dwt_elapsed_us(t0) > I2C_TIMEOUT_US) return -1;
    }
    LPI2C0->MTDR = word;
    return 0;
}

static void i2c_recover(void)
{
    LPI2C0->MCR |= (1u << 8);                              // RTF : reset transmit FIFO
    LPI2C0->MSR  = LPI2C_MSR_NDF_MASK | LPI2C_MSR_ALF_MASK | LPI2C_MSR_FEF_MASK | LPI2C_MSR_PLTF_MASK
                 | LPI2C_MSR_EPF_MASK | LPI2C_MSR_SDF_MASK;
}

// one I2C write transaction : START, addr+W, control byte, n data bytes, STOP
static int oled_write(uint8_t control, const uint8_t *buf, int n)
{
    uint32_t t0;
    int i;

    LPI2C0->MSR = LPI2C_MSR_NDF_MASK | LPI2C_MSR_ALF_MASK | LPI2C_MSR_FEF_MASK | LPI2C_MSR_PLTF_MASK
                | LPI2C_MSR_EPF_MASK | LPI2C_MSR_SDF_MASK;

    if (i2c_push(LPI2C_MTDR_CMD(4) | LPI2C_MTDR_DATA((uint32_t)oled_addr << 1)) < 0) goto fail;   // START + address
    if (i2c_push(LPI2C_MTDR_CMD(0) | LPI2C_MTDR_DATA(control)) < 0) goto fail;
    for (i = 0; i < n; i++) {
        if (i2c_push(LPI2C_MTDR_CMD(0) | LPI2C_MTDR_DATA(buf[i])) < 0) goto fail;
    }
    if (i2c_push(LPI2C_MTDR_CMD(2)) < 0) goto fail;                                               // STOP

    t0 = dwt_now();
    while ((LPI2C0->MSR & LPI2C_MSR_SDF_MASK) == 0) {       // wait for STOP to go out
        if (LPI2C0->MSR & LPI2C_MSR_NDF_MASK) goto fail;
        if (dwt_elapsed_us(t0) > I2C_TIMEOUT_US) goto fail;
    }
    if (LPI2C0->MSR & LPI2C_MSR_NDF_MASK) goto fail;
    oled_err = 0;
    return 0;

fail:
    i2c_recover();
    oled_err = -1;
    return -1;
}

static int oled_cmd(uint8_t c)                 { return oled_write(0x00, &c, 1); }
static int oled_data(const uint8_t *d, int n)  { return oled_write(0x40, d, n); }

// ---------------- SSD1306 ----------------
static const uint8_t INIT_SEQ[] = {
    0xAE,              // display off
    0xD5, 0x80,        // clock divide
    0xA8, OLED_HEIGHT - 1,   // multiplex ratio
    0xD3, 0x00,        // display offset
    0x40,              // start line 0
    0x8D, 0x14,        // charge pump on
    0x20, 0x02,        // page addressing mode
    0xA1,              // segment remap (column 127 = SEG0)
    0xC8,              // COM scan direction remapped
    0xDA, (OLED_HEIGHT == 64) ? 0x12 : 0x02,   // COM pins
    0x81, 0xCF,        // contrast
    0xD9, 0xF1,        // precharge
    0xDB, 0x40,        // VCOMH
    0xA4,              // resume from RAM
    0xA6,              // normal (not inverted)
    0x2E,              // scroll off
    0xAF,              // display on
};

static int oled_set_pos(uint8_t page, uint8_t x)
{
    uint8_t c[3] = { (uint8_t)(0xB0 | (page & 0x07)), (uint8_t)(0x00 | (x & 0x0F)), (uint8_t)(0x10 | (x >> 4)) };
    return oled_write(0x00, c, 3);
}

int OLED_init(void)
{
    uint8_t probe = 0xAE;

    LPI2C0_init();
    delay_ms(100);                                         // display power-up time

    oled_addr = 0x3C;
    if (oled_write(0x00, &probe, 1) < 0) {                 // no ACK at 0x3C -> try 0x3D
        oled_addr = 0x3D;
        if (oled_write(0x00, &probe, 1) < 0) {
            return -1;
        }
    }
    if (oled_write(0x00, INIT_SEQ, (int)sizeof(INIT_SEQ)) < 0) return -1;
    OLED_clear();
    return oled_err;
}

void OLED_clear(void)
{
    static const uint8_t zeros[32] = {0};
    for (uint8_t p = 0; p < OLED_ROWS; p++) {
        oled_set_pos(p, 0);
        for (int k = 0; k < OLED_WIDTH / 32; k++) {
            oled_data(zeros, 32);
        }
    }
}

void OLED_puts(uint8_t row, uint8_t col, const char *s)
{
    uint8_t glyph[6];
    if (row >= OLED_ROWS) return;
    oled_set_pos(row, (uint8_t)(col * 6));
    while (*s && col < OLED_COLS) {
        uint8_t c = (uint8_t)*s++;
        if (c < 0x20 || c > 0x7E) c = '?';
        for (int i = 0; i < 5; i++) glyph[i] = FONT5X7[c - 0x20][i];
        glyph[5] = 0x00;                                   // 1 pixel gap
        if (oled_data(glyph, 6) < 0) return;
        col++;
    }
}

void OLED_put_uint(uint8_t row, uint8_t col, uint32_t v, uint8_t width)
{
    char buf[12];
    int  i = 11;
    buf[i] = '\0';
    do {
        buf[--i] = (char)('0' + v % 10);
        v /= 10;
    } while (v && i > 0);
    while (i > 0 && (11 - i) < width) buf[--i] = ' ';     // pad on the left
    OLED_puts(row, col, &buf[i]);
}

void OLED_put_int(uint8_t row, uint8_t col, int32_t v, uint8_t width)
{
    if (v < 0) {
        OLED_puts(row, col, "-");
        OLED_put_uint(row, (uint8_t)(col + 1), (uint32_t)(-v), (uint8_t)(width ? width - 1 : 0));
    } else {
        OLED_put_uint(row, col, (uint32_t)v, width);
    }
}

int     OLED_last_error(void) { return oled_err; }
uint8_t OLED_address(void)    { return oled_addr; }
